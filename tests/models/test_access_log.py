class TestAccessLogQuery:
    """Tests for AccessLog query functionality."""
    
    @pytest.fixture
    def populated_log(self):
        """Create a log with various entries for testing queries."""
        log = AccessLog()
        now = datetime.now(timezone.utc)
        
        # Add entries with different characteristics
        entries = [
            # Success entries
            AccessLogEntry(
                log_id="entry-1",
                timestamp=now - timedelta(hours=2),
                method="GET",
                path="/email/state",
                key_id="ues_key1",
                key_name="Bot 1",
                status_code=200,
                duration_ms=10.0,
            ),
            AccessLogEntry(
                log_id="entry-2",
                timestamp=now - timedelta(hours=1),
                method="POST",
                path="/email/send",
                key_id="ues_key1",
                key_name="Bot 1",
                status_code=201,
                duration_ms=50.0,
            ),
            # Different key
            AccessLogEntry(
                log_id="entry-3",
                timestamp=now - timedelta(minutes=30),
                method="GET",
                path="/sms/state",
                key_id="ues_key2",
                key_name="Bot 2",
                status_code=200,
                duration_ms=15.0,
            ),
            # Error entries
            AccessLogEntry(
                log_id="entry-4",
                timestamp=now - timedelta(minutes=15),
                method="POST",
                path="/email/send",
                key_id="ues_key1",
                key_name="Bot 1",
                status_code=400,
                duration_ms=5.0,
                error_detail="Invalid request",
            ),
            AccessLogEntry(
                log_id="entry-5",
                timestamp=now - timedelta(minutes=5),
                method="GET",
                path="/calendar/state",
                key_id="ues_key1",
                key_name="Bot 1",
                status_code=500,
                duration_ms=100.0,
                error_detail="Server error",
            ),
        ]
        
        for entry in entries:
            log.log(entry)
        
        return log, now
    
    def test_query_no_filters(self, populated_log):
        """Test query with no filters returns all entries (newest first)."""
        log, _ = populated_log
        
        results = log.query()
        
        assert len(results) == 5
        # Should be newest first
        assert results[0].log_id == "entry-5"
        assert results[-1].log_id == "entry-1"
    
    def test_query_by_key_id(self, populated_log):
        """Test query filtering by key_id."""
        log, _ = populated_log
        
        results = log.query(key_id="ues_key1")
        
        assert len(results) == 4
        assert all(e.key_id == "ues_key1" for e in results)
    
    def test_query_by_key_name(self, populated_log):
        """Test query filtering by key_name."""
        log, _ = populated_log
        
        results = log.query(key_name="Bot 2")
        
        assert len(results) == 1
        assert results[0].key_name == "Bot 2"
    
    def test_query_by_path_prefix(self, populated_log):
        """Test query filtering by path prefix."""
        log, _ = populated_log
        
        results = log.query(path_prefix="/email")
        
        assert len(results) == 3
        assert all(e.path.startswith("/email") for e in results)
    
    def test_query_by_method(self, populated_log):
        """Test query filtering by HTTP method."""
        log, _ = populated_log
        
        results = log.query(method="GET")
        
        assert len(results) == 3
        assert all(e.method == "GET" for e in results)
    
    def test_query_by_method_case_insensitive(self, populated_log):
        """Test that method filter is case-insensitive."""
        log, _ = populated_log
        
        results_lower = log.query(method="get")
        results_upper = log.query(method="GET")
        results_mixed = log.query(method="Get")
        
        assert len(results_lower) == len(results_upper) == len(results_mixed) == 3
    
    def test_query_by_exact_status_code(self, populated_log):
        """Test query filtering by exact status code."""
        log, _ = populated_log
        
        results = log.query(status_code=200)
        
        assert len(results) == 2
        assert all(e.status_code == 200 for e in results)
    
    def test_query_by_status_code_range(self, populated_log):
        """Test query filtering by status code range."""
        log, _ = populated_log
        
        # Get all success responses (200-299)
        results = log.query(min_status_code=200, max_status_code=299)
        
        assert len(results) == 3
        assert all(200 <= e.status_code <= 299 for e in results)
    
    def test_query_by_min_status_code(self, populated_log):
        """Test query filtering by minimum status code."""
        log, _ = populated_log
        
        results = log.query(min_status_code=400)
        
        assert len(results) == 2
        assert all(e.status_code >= 400 for e in results)
    
    def test_query_by_max_status_code(self, populated_log):
        """Test query filtering by maximum status code."""
        log, _ = populated_log
        
        results = log.query(max_status_code=201)
        
        assert len(results) == 3
        assert all(e.status_code <= 201 for e in results)
    
    def test_query_since_timestamp(self, populated_log):
        """Test query filtering by since timestamp."""
        log, now = populated_log
        
        since = now - timedelta(minutes=20)
        results = log.query(since=since)
        
        assert len(results) == 2  # entry-4 (15 min ago) and entry-5 (5 min ago)
        assert all(e.timestamp >= since for e in results)
    
    def test_query_until_timestamp(self, populated_log):
        """Test query filtering by until timestamp."""
        log, now = populated_log
        
        until = now - timedelta(minutes=20)
        results = log.query(until=until)
        
        assert len(results) == 3  # entry-1, entry-2, entry-3
        assert all(e.timestamp < until for e in results)
    
    def test_query_timestamp_range(self, populated_log):
        """Test query filtering by timestamp range."""
        log, now = populated_log
        
        since = now - timedelta(minutes=45)
        until = now - timedelta(minutes=10)
        results = log.query(since=since, until=until)
        
        assert len(results) == 2  # entry-3 (30 min ago) and entry-4 (15 min ago)
    
    def test_query_errors_only(self, populated_log):
        """Test query filtering for errors only."""
        log, _ = populated_log
        
        results = log.query(errors_only=True)
        
        assert len(results) == 2
        assert all(e.is_error for e in results)
    
    def test_query_with_limit(self, populated_log):
        """Test query with limit."""
        log, _ = populated_log
        
        results = log.query(limit=2)
        
        assert len(results) == 2
        # Should be the 2 newest entries
        assert results[0].log_id == "entry-5"
        assert results[1].log_id == "entry-4"
    
    def test_query_with_offset(self, populated_log):
        """Test query with offset."""
        log, _ = populated_log
        
        results = log.query(offset=2)
        
        assert len(results) == 3
        # Should skip 2 newest, get entries 3, 2, 1
        assert results[0].log_id == "entry-3"
        assert results[-1].log_id == "entry-1"
    
    def test_query_with_limit_and_offset(self, populated_log):
        """Test query with both limit and offset (pagination)."""
        log, _ = populated_log
        
        # Get page 2 with page size 2
        results = log.query(limit=2, offset=2)
        
        assert len(results) == 2
        assert results[0].log_id == "entry-3"
        assert results[1].log_id == "entry-2"
    
    def test_query_combined_filters(self, populated_log):
        """Test query with multiple filters combined."""
        log, _ = populated_log
        
        results = log.query(
            key_id="ues_key1",
            method="POST",
            path_prefix="/email",
        )
        
        assert len(results) == 2  # entry-2 (201) and entry-4 (400)
        assert all(e.key_id == "ues_key1" for e in results)
        assert all(e.method == "POST" for e in results)
