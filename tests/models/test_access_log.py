class TestHelperFunctions:
    """Tests for module-level helper functions."""
    
    def test_generate_log_id_is_uuid(self):
        """Test that generate_log_id returns a valid UUID string."""
        log_id = generate_log_id()
        
        # UUID format: 8-4-4-4-12 hex characters with dashes
        assert len(log_id) == 36
        parts = log_id.split("-")
        assert len(parts) == 5
        assert [len(p) for p in parts] == [8, 4, 4, 4, 12]
    
    def test_generate_log_id_unique(self):
        """Test that generate_log_id returns unique values."""
        ids = [generate_log_id() for _ in range(100)]
        
        assert len(ids) == len(set(ids))


