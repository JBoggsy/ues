class TestAccessLogStatistics:
    """Tests for AccessLog statistics functionality."""
    
    def test_statistics_empty_log(self):
        """Test statistics on empty log."""
        log = AccessLog()
        
        stats = log.get_statistics()
        
        assert stats["total_entries"] == 0
        assert stats["success_count"] == 0
        assert stats["client_error_count"] == 0
        assert stats["server_error_count"] == 0
        assert stats["unique_keys"] == 0
        assert stats["earliest_timestamp"] is None
        assert stats["latest_timestamp"] is None
    
    def test_statistics_with_entries(self):
        """Test statistics with various entries."""
        log = AccessLog()
        now = datetime.now(timezone.utc)
        
        # Add entries with different status codes and keys
        log.log(AccessLogEntry(
            timestamp=now - timedelta(hours=1),
            method="GET",
            path="/test",
            key_id="key1",
            status_code=200,
            duration_ms=1.0,
        ))
        log.log(AccessLogEntry(
            timestamp=now - timedelta(minutes=30),
            method="GET",
            path="/test",
            key_id="key1",
            status_code=201,
            duration_ms=1.0,
        ))
        log.log(AccessLogEntry(
            timestamp=now - timedelta(minutes=15),
            method="GET",
            path="/test",
            key_id="key2",
            status_code=400,
            duration_ms=1.0,
        ))
        log.log(AccessLogEntry(
            timestamp=now,
            method="GET",
            path="/test",
            key_id=None,  # Unauthenticated
            status_code=500,
            duration_ms=1.0,
        ))
        
        stats = log.get_statistics()
        
        assert stats["total_entries"] == 4
        assert stats["success_count"] == 2  # 200, 201
        assert stats["client_error_count"] == 1  # 400
        assert stats["server_error_count"] == 1  # 500
        assert stats["unique_keys"] == 3  # key1, key2, None
    
    def test_statistics_timestamps(self):
        """Test that statistics include correct timestamp range."""
        log = AccessLog()
        
        earliest = datetime(2024, 1, 1, 10, 0, 0, tzinfo=timezone.utc)
        latest = datetime(2024, 1, 1, 12, 0, 0, tzinfo=timezone.utc)
        
        log.log(AccessLogEntry(
            timestamp=earliest,
            method="GET",
            path="/test",
            status_code=200,
            duration_ms=1.0,
        ))
        log.log(AccessLogEntry(
            timestamp=datetime(2024, 1, 1, 11, 0, 0, tzinfo=timezone.utc),
            method="GET",
            path="/test",
            status_code=200,
            duration_ms=1.0,
        ))
        log.log(AccessLogEntry(
            timestamp=latest,
            method="GET",
            path="/test",
            status_code=200,
            duration_ms=1.0,
        ))
        
        stats = log.get_statistics()
        
        assert stats["earliest_timestamp"] == earliest
        assert stats["latest_timestamp"] == latest
    
    def test_statistics_3xx_not_counted_as_error(self):
        """Test that 3xx responses are not counted as errors."""
        log = AccessLog()
        
        log.log(AccessLogEntry(
            method="GET", path="/test", status_code=301, duration_ms=1.0
        ))
        log.log(AccessLogEntry(
            method="GET", path="/test", status_code=302, duration_ms=1.0
        ))
        
        stats = log.get_statistics()
        
        assert stats["total_entries"] == 2
        assert stats["success_count"] == 0
        assert stats["client_error_count"] == 0
        assert stats["server_error_count"] == 0
