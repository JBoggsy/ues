class TestAccessLog:
    """Tests for AccessLog basic operations."""
    
    def test_instantiation_default_max_entries(self):
        """Test AccessLog with default max_entries."""
        log = AccessLog()
        
        assert log.max_entries == 10000
        assert log.count == 0
        assert log.is_full is False
    
    def test_instantiation_custom_max_entries(self):
        """Test AccessLog with custom max_entries."""
        log = AccessLog(max_entries=100)
        
        assert log.max_entries == 100
    
    def test_instantiation_invalid_max_entries(self):
        """Test that max_entries must be at least 1."""
        with pytest.raises(ValueError, match="max_entries must be at least 1"):
            AccessLog(max_entries=0)
        
        with pytest.raises(ValueError, match="max_entries must be at least 1"):
            AccessLog(max_entries=-5)
    
    def test_log_single_entry(self):
        """Test logging a single entry."""
        log = AccessLog()
        entry = AccessLogEntry(
            method="GET", path="/test", status_code=200, duration_ms=1.0
        )
        
        log.log(entry)
        
        assert log.count == 1
    
    def test_log_multiple_entries(self):
        """Test logging multiple entries."""
        log = AccessLog()
        
        for i in range(5):
            entry = AccessLogEntry(
                method="GET", path=f"/test/{i}", status_code=200, duration_ms=1.0
            )
            log.log(entry)
        
        assert log.count == 5
    
    def test_log_respects_max_entries(self):
        """Test that log respects max_entries limit."""
        log = AccessLog(max_entries=5)
        
        # Log 10 entries
        for i in range(10):
            entry = AccessLogEntry(
                log_id=f"entry-{i}",
                method="GET",
                path=f"/test/{i}",
                status_code=200,
                duration_ms=1.0,
            )
            log.log(entry)
        
        assert log.count == 5
        assert log.is_full is True
        
        # Verify oldest entries were removed (entries 0-4 should be gone)
        assert log.get_by_id("entry-0") is None
        assert log.get_by_id("entry-4") is None
        # Newest entries should remain
        assert log.get_by_id("entry-5") is not None
        assert log.get_by_id("entry-9") is not None
    
    def test_get_by_id_found(self):
        """Test get_by_id when entry exists."""
        log = AccessLog()
        entry = AccessLogEntry(
            log_id="test-123",
            method="GET",
            path="/test",
            status_code=200,
            duration_ms=1.0,
        )
        log.log(entry)
        
        found = log.get_by_id("test-123")
        
        assert found is not None
        assert found.log_id == "test-123"
    
    def test_get_by_id_not_found(self):
        """Test get_by_id when entry doesn't exist."""
        log = AccessLog()
        entry = AccessLogEntry(
            log_id="test-123",
            method="GET",
            path="/test",
            status_code=200,
            duration_ms=1.0,
        )
        log.log(entry)
        
        found = log.get_by_id("nonexistent")
        
        assert found is None
    
    def test_clear_empty_log(self):
        """Test clearing an empty log."""
        log = AccessLog()
        
        cleared = log.clear()
        
        assert cleared == 0
        assert log.count == 0
    
    def test_clear_populated_log(self):
        """Test clearing a populated log."""
        log = AccessLog()
        for i in range(5):
            log.log(AccessLogEntry(
                method="GET", path="/test", status_code=200, duration_ms=1.0
            ))
        
        cleared = log.clear()
        
        assert cleared == 5
        assert log.count == 0
    
    def test_is_full_property(self):
        """Test is_full property."""
        log = AccessLog(max_entries=3)
        
        assert log.is_full is False
        
        log.log(AccessLogEntry(method="GET", path="/1", status_code=200, duration_ms=1.0))
        assert log.is_full is False
        
        log.log(AccessLogEntry(method="GET", path="/2", status_code=200, duration_ms=1.0))
        assert log.is_full is False
        
        log.log(AccessLogEntry(method="GET", path="/3", status_code=200, duration_ms=1.0))
        assert log.is_full is True


